// Generates the known-good SorobanAuthorization preimage reference using the
// official JS SDK. Output is committed as a fixture; the Rust implementation
// must reproduce these bytes exactly.
const { xdr, hash, Keypair, Networks, Address, nativeToScVal, authorizeEntry } =
  require('@stellar/stellar-sdk');

const NONCE = '1234567890';
const EXPIRATION = 1000;

// deterministic inputs so the fixture is reproducible
const contractId = Buffer.alloc(32, 1);
const contractAddress = Address.contract(contractId);
const from = Keypair.fromRawEd25519Seed(Buffer.alloc(32, 7));
const to = Keypair.fromRawEd25519Seed(Buffer.alloc(32, 9));

const invocation = new xdr.SorobanAuthorizedInvocation({
  function: xdr.SorobanAuthorizedFunction.sorobanAuthorizedFunctionTypeContractFn(
    new xdr.InvokeContractArgs({
      contractAddress: contractAddress.toScAddress(),
      functionName: 'transfer',
      args: [
        new Address(from.publicKey()).toScVal(),
        new Address(to.publicKey()).toScVal(),
        nativeToScVal(1000000n, { type: 'i128' }),
      ],
    })
  ),
  subInvocations: [],
});

const networkId = hash(Buffer.from(Networks.TESTNET));

const preimage = xdr.HashIdPreimage.envelopeTypeSorobanAuthorization(
  new xdr.HashIdPreimageSorobanAuthorization({
    networkId,
    nonce: xdr.Int64.fromString(NONCE),
    signatureExpirationLedger: EXPIRATION,
    invocation,
  })
);

const preimageXdr = preimage.toXDR();
const payload = hash(preimageXdr);

const out = {
  note: 'Generated by @stellar/stellar-sdk. Do not hand-edit.',
  sdkVersion: JSON.parse(
    require('fs').readFileSync('node_modules/@stellar/stellar-sdk/package.json', 'utf8')
  ).version,
  networkPassphrase: Networks.TESTNET,
  networkIdHex: networkId.toString('hex'),
  nonce: NONCE,
  signatureExpirationLedger: EXPIRATION,
  contractIdHex: contractId.toString('hex'),
  fromPublicKey: from.publicKey(),
  toPublicKey: to.publicKey(),
  amountI128: '1000000',
  invocationXdrBase64: invocation.toXDR('base64'),
  preimageXdrBase64: preimageXdr.toString('base64'),
  preimageSha256Hex: payload.toString('hex'),
};

console.log(JSON.stringify(out, null, 2));
